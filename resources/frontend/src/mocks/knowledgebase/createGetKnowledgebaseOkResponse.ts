import {
  type KnowledgebaseCollectionResponse,
  type KnowledgebaseResponse,
} from "../../types/knowledgebase";

export function createGetKnowledgebaseOkResponse({
  isLoggedIn,
  numberOfKnowledgebase,
  page = 1,
  total,
}: {
  isLoggedIn: boolean;
  numberOfKnowledgebase?: number;
  page?: 1 | 2;
  total?: number;
}): KnowledgebaseCollectionResponse {
  const knowledgebase = isLoggedIn ? allKnowledgebase : publicKnowledgebase;

  const pageSlice = numberOfKnowledgebase ?? 10;

  const knowledgebaseResponse =
    page === 1
      ? knowledgebase.slice(0, pageSlice)
      : knowledgebase.slice(pageSlice);

  return {
    data: knowledgebaseResponse,
    meta: {
      count: numberOfKnowledgebase ?? knowledgebase.length,
      total: total ?? knowledgebase.length,
    },
  };
}

